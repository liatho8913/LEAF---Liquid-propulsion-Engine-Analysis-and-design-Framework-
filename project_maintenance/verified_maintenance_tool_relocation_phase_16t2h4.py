from __future__ import annotations

import argparse
import csv
import shutil
import sys
import zipfile
from datetime import datetime
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))


PHASE = "16T.2H.4"

PASS_STATUS = "PASS_VERIFIED_MAINTENANCE_TOOL_RELOCATION_PHASE_16T2H4"
WARN_STATUS = "WARN_VERIFIED_MAINTENANCE_TOOL_RELOCATION_PHASE_16T2H4"
FAIL_STATUS = "FAIL_VERIFIED_MAINTENANCE_TOOL_RELOCATION_PHASE_16T2H4"

PLAN_PATH = ROOT / "_leaf_artifacts" / "allowlists" / "MAINTENANCE_TOOL_RELOCATION_PLAN_PHASE_16T2H3.tsv"
REPORT_DIR = ROOT / "_leaf_artifacts" / "reports"
ZIP_DIR = ROOT / "_leaf_artifacts" / "zips"


def _timestamp() -> str:
    return datetime.now().strftime("%Y%m%d_%H%M%S")


def _read_plan() -> list[dict[str, str]]:
    if not PLAN_PATH.exists():
        return []

    rows: list[dict[str, str]] = []

    with PLAN_PATH.open("r", encoding="utf-8") as f:
        reader = csv.DictReader(f, delimiter="\t")
        for row in reader:
            if row.get("action") == "PLAN_MOVE":
                rows.append(row)

    return rows


def _module_path_from_relative(relative_path: str) -> str:
    return Path(relative_path).with_suffix("").as_posix().replace("/", ".")


def _wrapper_text(source_rel: str, target_rel: str) -> str:
    target_module = _module_path_from_relative(target_rel)

    return f'''"""
Compatibility wrapper generated by PHASE 16T.2H.4.

Original maintenance tool was relocated from:
    {source_rel}

New authoritative location:
    {target_rel}

This wrapper exists to preserve old imports during transition.
It can be removed only after post-relocation validation confirms no old imports remain.
"""

from {target_module} import *  # noqa: F401,F403
'''


def build_verified_relocation_plan() -> dict[str, Any]:
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    ZIP_DIR.mkdir(parents=True, exist_ok=True)

    rows = _read_plan()

    blockers: list[str] = []
    warnings: list[str] = []
    items: list[dict[str, Any]] = []

    if not PLAN_PATH.exists():
        blockers.append(f"Relocation plan missing: {PLAN_PATH}")

    if not rows:
        blockers.append("Relocation plan contains no PLAN_MOVE entries.")

    for row in rows:
        source_rel = row["source"]
        target_rel = row["target"]

        source = ROOT / source_rel
        target = ROOT / target_rel

        source_exists = source.exists()
        target_exists = target.exists()

        if not source_exists and not target_exists:
            blockers.append(f"Neither source nor target exists for relocation: {source_rel}")

        if source_exists and target_exists:
            warnings.append(f"Both source and target already exist: {source_rel} -> {target_rel}")

        items.append(
            {
                "source": source_rel,
                "target": target_rel,
                "source_exists": source_exists,
                "target_exists": target_exists,
                "will_move": source_exists and not target_exists,
                "will_create_wrapper": source_exists,
                "reason": row.get("reason", ""),
            }
        )

    status = FAIL_STATUS if blockers else WARN_STATUS if warnings else PASS_STATUS

    return {
        "phase": PHASE,
        "status": status,
        "passed": not blockers,
        "plan_path": str(PLAN_PATH),
        "item_count": len(items),
        "move_count": sum(1 for item in items if item["will_move"]),
        "wrapper_count": sum(1 for item in items if item["will_create_wrapper"]),
        "items": items,
        "warnings": warnings,
        "blockers": blockers,
        "summary": (
            f"{len(items)} maintenance relocation entries checked; "
            f"{sum(1 for item in items if item['will_move'])} ready to move; "
            f"{sum(1 for item in items if item['will_create_wrapper'])} wrappers planned."
        ),
    }


def build_verified_relocation_report(plan: dict[str, Any], executed: bool = False, backup_zip: str | None = None) -> str:
    lines = [
        "VERIFIED MAINTENANCE TOOL RELOCATION",
        "====================================",
        f"Phase: {plan['phase']}",
        f"Status: {plan['status']}",
        f"Passed: {plan['passed']}",
        f"Executed: {executed}",
        f"Summary: {plan['summary']}",
        f"Plan file: {plan['plan_path']}",
    ]

    if backup_zip:
        lines.append(f"Backup zip: {backup_zip}")

    lines.extend([
        "",
        "COUNTS",
        "------",
        f"Relocation entries: {plan['item_count']}",
        f"Files ready to move: {plan['move_count']}",
        f"Compatibility wrappers planned: {plan['wrapper_count']}",
        "",
        "RELOCATION PLAN",
        "---------------",
    ])

    for item in plan["items"]:
        lines.append(
            f"- {item['source']} -> {item['target']} | "
            f"source_exists={item['source_exists']} | "
            f"target_exists={item['target_exists']} | "
            f"will_move={item['will_move']} | "
            f"wrapper={item['will_create_wrapper']} | "
            f"{item['reason']}"
        )

    if plan["warnings"]:
        lines.extend(["", "WARNINGS", "--------"])
        lines.extend(f"- {warning}" for warning in plan["warnings"])

    if plan["blockers"]:
        lines.extend(["", "BLOCKERS", "--------"])
        lines.extend(f"- {blocker}" for blocker in plan["blockers"])

    lines.extend([
        "",
        "SAFETY GUARANTEE",
        "----------------",
        "This phase deletes nothing. It creates a zip backup, moves planned files, and leaves compatibility wrappers at old import paths.",
    ])

    return "\n".join(lines)


def _write_report(text: str, filename: str) -> Path:
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    output = REPORT_DIR / filename
    output.write_text(text, encoding="utf-8")
    return output


def _create_backup_zip(plan: dict[str, Any]) -> Path:
    ZIP_DIR.mkdir(parents=True, exist_ok=True)
    zip_path = ZIP_DIR / f"LEAF_PHASE_16T2H4_MAINTENANCE_RELOCATION_BACKUP_{_timestamp()}.zip"

    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for item in plan["items"]:
            source = ROOT / item["source"]
            target = ROOT / item["target"]

            if source.exists():
                zf.write(source, source.relative_to(ROOT).as_posix())

            if target.exists():
                zf.write(target, target.relative_to(ROOT).as_posix())

    return zip_path


def execute_verified_relocation() -> dict[str, Any]:
    plan = build_verified_relocation_plan()

    if plan["blockers"]:
        report_path = _write_report(
            build_verified_relocation_report(plan, executed=False),
            "VERIFIED_MAINTENANCE_TOOL_RELOCATION_BLOCKED_PHASE_16T2H4.txt",
        )
        return {
            "status": FAIL_STATUS,
            "executed": False,
            "moved_count": 0,
            "wrapper_count": 0,
            "backup_zip": None,
            "report_path": str(report_path),
        }

    backup_zip = _create_backup_zip(plan)

    moved: list[str] = []
    wrappers: list[str] = []

    for item in plan["items"]:
        source = ROOT / item["source"]
        target = ROOT / item["target"]

        if item["will_move"]:
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(source), str(target))
            moved.append(item["source"])

            source.parent.mkdir(parents=True, exist_ok=True)
            source.write_text(_wrapper_text(item["source"], item["target"]), encoding="utf-8")
            wrappers.append(item["source"])

    post_plan = build_verified_relocation_plan()
    report_path = _write_report(
        build_verified_relocation_report(post_plan, executed=True, backup_zip=str(backup_zip)),
        "VERIFIED_MAINTENANCE_TOOL_RELOCATION_EXECUTED_PHASE_16T2H4.txt",
    )

    return {
        "status": PASS_STATUS,
        "executed": True,
        "moved_count": len(moved),
        "wrapper_count": len(wrappers),
        "moved": moved,
        "wrappers": wrappers,
        "backup_zip": str(backup_zip),
        "report_path": str(report_path),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--execute", action="store_true")
    args = parser.parse_args()

    plan = build_verified_relocation_plan()

    if not args.execute:
        report_path = _write_report(
            build_verified_relocation_report(plan, executed=False),
            "VERIFIED_MAINTENANCE_TOOL_RELOCATION_DRY_RUN_PHASE_16T2H4.txt",
        )
        print(plan["status"])
        print(report_path)
        print("DRY_RUN_ONLY")
        return 0 if plan["passed"] else 1

    result = execute_verified_relocation()
    print(result["status"])
    print(result["report_path"])
    if result["backup_zip"]:
        print(result["backup_zip"])
    print(f"moved_count={result['moved_count']}")
    print(f"wrapper_count={result['wrapper_count']}")
    return 0 if result["status"] == PASS_STATUS else 1


if __name__ == "__main__":
    raise SystemExit(main())
